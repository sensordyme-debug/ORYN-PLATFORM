-- ORYN 0001 — foundation: extensions, roles, tenant context, identity, tenancy, audit.
--
-- Tenant isolation model
--   Every tenant-owned table carries org_id and has row-level security enabled.
--   The application connects as a member of oryn_app_role (no BYPASSRLS) and
--   sets transaction-local context:
--     app.org_id   the organization the current unit of work acts for
--     app.user_id  the authenticated user (used to list the user's own orgs)
--     app.system   'on' only for deliberate cross-tenant platform operations
--   Application code ALSO filters by org_id explicitly; RLS is the second wall.

create extension if not exists postgis;
create extension if not exists citext;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'oryn_app_role') then
    create role oryn_app_role nologin;
  end if;
end
$$;

grant usage on schema public to oryn_app_role;
alter default privileges in schema public grant select, insert, update, delete on tables to oryn_app_role;
alter default privileges in schema public grant usage, select on sequences to oryn_app_role;
alter default privileges in schema public grant execute on functions to oryn_app_role;
grant select on spatial_ref_sys to oryn_app_role;

-- ── Context helpers ──────────────────────────────────────────

create function app_current_org() returns uuid
  language sql stable
  as $$ select nullif(current_setting('app.org_id', true), '')::uuid $$;

create function app_current_user() returns text
  language sql stable
  as $$ select nullif(current_setting('app.user_id', true), '') $$;

create function app_is_system() returns boolean
  language sql stable
  as $$ select coalesce(current_setting('app.system', true), '') = 'on' $$;

create function touch_updated_at() returns trigger
  language plpgsql
  as $$ begin new.updated_at := now(); return new; end $$;

-- Enables RLS on a tenant table with the standard isolation policy.
create function enable_tenant_rls(tbl regclass) returns void
  language plpgsql
  as $$
  begin
    execute format('alter table %s enable row level security', tbl);
    execute format(
      'create policy tenant_isolation on %s using (app_is_system() or org_id = app_current_org()) '
      'with check (app_is_system() or org_id = app_current_org())', tbl);
  end
  $$;
revoke execute on function enable_tenant_rls(regclass) from public, oryn_app_role;

