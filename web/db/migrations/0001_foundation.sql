-- ── Organizations and membership ─────────────────────────────

create type org_kind as enum ('agriculture', 'municipal', 'infrastructure', 'enterprise', 'public_sector');
create type org_role as enum ('org_admin', 'analyst', 'field_operator', 'viewer', 'auditor');

create table organizations (
  id uuid primary key default gen_random_uuid(),
  slug citext not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,47}$'),
  name text not null check (char_length(name) between 2 and 120),
  kind org_kind not null,
  -- Synthetic organizations hold development sample data only.
  is_synthetic boolean not null default false,
  settings jsonb not null default '{}'::jsonb,
  onboarding_completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz
);
create trigger organizations_touch before update on organizations for each row execute function touch_updated_at();

create table memberships (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references organizations (id) on delete cascade,
  user_id text not null references "auth_user" ("id") on delete cascade,
  role org_role not null,
  -- When true, the member sees only AOIs explicitly granted in aoi_grants.
  aoi_restricted boolean not null default false,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, user_id)
);
create index memberships_user on memberships (user_id);
create trigger memberships_touch before update on memberships for each row execute function touch_updated_at();

alter table organizations enable row level security;
create policy org_select on organizations for select using (
  app_is_system()
  or id = app_current_org()
  or exists (select 1 from memberships m where m.org_id = organizations.id and m.user_id = app_current_user())
);
create policy org_update on organizations for update
  using (app_is_system() or id = app_current_org())
  with check (app_is_system() or id = app_current_org());
create policy org_insert on organizations for insert with check (app_is_system());
create policy org_delete on organizations for delete using (app_is_system());

alter table memberships enable row level security;
create policy membership_select_own on memberships for select using (user_id = app_current_user());
create policy tenant_isolation on memberships
  using (app_is_system() or org_id = app_current_org())
  with check (app_is_system() or org_id = app_current_org());

create table invitations (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references organizations (id) on delete cascade,
  email citext not null,
  role org_role not null,
  token_hash bytea not null unique,
  invited_by text references "auth_user" ("id") on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  accepted_by text references "auth_user" ("id") on delete set null,
  revoked_at timestamptz
);
create unique index invitations_one_pending on invitations (org_id, email) where accepted_at is null and revoked_at is null;
select enable_tenant_rls('invitations');

-- Pre-tenant lookups. SECURITY DEFINER functions expose exactly one fact each
-- and run with a fixed search_path.
create function auth_has_pending_invitation(p_email text) returns boolean
  language sql stable security definer set search_path = public, pg_temp
  as $$
    select exists (
      select 1 from invitations
       where email = p_email::citext and accepted_at is null and revoked_at is null and expires_at > now())
  $$;

create function invitation_by_token(p_token_hash bytea)
  returns table (id uuid, org_id uuid, org_name text, email text, role org_role,
                 expires_at timestamptz, accepted_at timestamptz, revoked_at timestamptz)
  language sql stable security definer set search_path = public, pg_temp
  as $$
    select i.id, i.org_id, o.name, i.email::text, i.role, i.expires_at, i.accepted_at, i.revoked_at
      from invitations i join organizations o on o.id = i.org_id
     where i.token_hash = p_token_hash
  $$;

-- ── API credentials ──────────────────────────────────────────
-- Keys are shown once at creation. Only a SHA-256 digest of the secret is
-- stored (the secret is 256 bits of CSPRNG output, so a fast hash is
-- appropriate; this is not password storage).

create table api_keys (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references organizations (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  prefix text not null unique,
  key_hash bytea not null unique,
  scopes text[] not null check (cardinality(scopes) > 0),
  created_by text references "auth_user" ("id") on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz,
  last_used_at timestamptz,
  revoked_at timestamptz
);
select enable_tenant_rls('api_keys');

create function api_key_by_prefix(p_prefix text)
  returns table (id uuid, org_id uuid, key_hash bytea, scopes text[], expires_at timestamptz, revoked_at timestamptz, created_by text)
  language sql stable security definer set search_path = public, pg_temp
  as $$ select id, org_id, key_hash, scopes, expires_at, revoked_at, created_by from api_keys where prefix = p_prefix $$;

-- ── Audit trail ──────────────────────────────────────────────
-- Append-only: the application role may insert and read (own org), never
-- update or delete. Retention purges go through purge_audit_events().

create table audit_events (
  id bigint generated always as identity primary key,
  org_id uuid references organizations (id) on delete set null,
  actor_type text not null check (actor_type in ('user', 'api_key', 'system')),
  actor_user_id text,
  actor_api_key_id uuid,
  actor_label text,
  action text not null,
  target_type text,
  target_id text,
  metadata jsonb not null default '{}'::jsonb,
  ip text,
  user_agent text,
  created_at timestamptz not null default now()
);
create index audit_events_org_time on audit_events (org_id, created_at desc);
create index audit_events_target on audit_events (target_type, target_id);
revoke update, delete on audit_events from oryn_app_role;

alter table audit_events enable row level security;
create policy audit_select on audit_events for select using (app_is_system() or org_id = app_current_org());
create policy audit_insert on audit_events for insert with check (
  app_is_system() or org_id = app_current_org() or (org_id is null and app_current_user() is not null)
);

create function audit_events_guard() returns trigger
  language plpgsql
  as $$
  begin
    if tg_op = 'DELETE' and coalesce(current_setting('app.audit_purge', true), '') = 'on' then
      return old;
    end if;
    raise exception 'audit_events is append-only' using errcode = '42501';
  end
  $$;
create trigger audit_events_append_only before update or delete on audit_events
  for each row execute function audit_events_guard();

create function purge_audit_events(p_org uuid, p_before timestamptz) returns integer
  language plpgsql security definer set search_path = public, pg_temp
  as $$
  declare n integer;
  begin
    if p_before > now() - interval '90 days' then
      raise exception 'audit events must be retained for at least 90 days';
    end if;
    perform set_config('app.audit_purge', 'on', true);
    delete from audit_events where org_id = p_org and created_at < p_before;
    get diagnostics n = row_count;
    perform set_config('app.audit_purge', '', true);
    return n;
  end
  $$;
